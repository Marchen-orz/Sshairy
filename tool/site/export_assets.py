"""Export what the landing page, README spreads and film share into site/.

python -I -X utf8 tool/site/export_assets.py [brand_pack_dir]
Writes resized brand artwork, the app's twelve palettes as CSS variables and the measured numbers.
The pack and the Dart sources stay untouched.
"""

import json
import re
import shutil
import sys
from pathlib import Path

from PIL import Image

REPO = Path(__file__).resolve().parents[2]
PACK = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO / 'Sshairy-Brand-Asset-Pack'
SITE = REPO / 'site'
OUT = SITE / 'assets'
THEMES = {
    'blue': '01-IceBlue-Mint', 'green': '02-MintGreen', 'violet': '03-Violet',
    'orange': '04-SunsetOrange', 'deepSea': '05-DeepSeaBlue', 'pink': '06-SakuraPink',
}
POSES = ['default', 'happy', 'speed', 'thinking-ai', 'success', 'security', 'sftp-transfer',
         'ssh-connected', 'coding-focus', 'sleeping']
# Normal Windows release artifacts, MiB; see tool/readme/SOURCES.md.
DOWNLOAD = [
    ('Sshairy', 27.2), ('WindTerm', 31.2), ('MobaXterm', 42.2), ('Xshell', 45.4), ('FinalShell', 63.8),
    ('electerm', 114.6), ('Netcatty', 126.9), ('Wave Terminal', 156.2), ('Tabby', 161.9), ('Termius', 327.9),
]
# Rounded MiB; the tiny files are grouped so the displayed parts total 97.4.
CONTENTS = [52.7, 20.3, 14.7, 5.6, 4.1]


def webp(source, target, size):
    image = Image.open(source).convert('RGBA')
    # Poses keep their shared square canvas so swapping one for another does not shift the character.
    image.thumbnail((size, size), Image.Resampling.LANCZOS)
    target.parent.mkdir(parents=True, exist_ok=True)
    image.save(target, 'WEBP', quality=90, method=6)


def artwork():
    palettes = {}
    for slug, folder in THEMES.items():
        source, target = PACK / folder, OUT / 'brand' / slug
        for pose in POSES:
            webp(source / f'poses/{pose}.png', target / f'{pose}.webp', 640)
        webp(source / 'logos/wordmark.png', target / 'wordmark.webp', 800)
        webp(source / 'app-icons/app-icon-256.png', target / 'icon.webp', 256)
        webp(REPO / f'assets/brand/{slug}/mark.png', target / 'mark.webp', 112)
        for name in ('breeze', 'cloud', 'sparkle', 'wind-lines'):
            shutil.copyfile(source / f'decorations/{name}.svg', target / f'{name}.svg')
        palettes[slug] = json.loads((source / 'palette/palette.json').read_text(encoding='utf-8'))['tokens']
    webp(PACK / '01-IceBlue-Mint/logos/wordmark-reverse.png', OUT / 'brand/blue/wordmark-reverse.webp', 800)
    Image.open(PACK / '01-IceBlue-Mint/app-icons/app-icon-64.png').save(OUT / 'favicon.png')
    airflow = Image.open(REPO / 'media/source/airflow.png').convert('RGB')
    airflow.save(OUT / 'airflow.webp', 'WEBP', quality=88, method=6)
    files = [path for path in (OUT / 'brand').rglob('*') if path.is_file()]
    assert len(files) == len(THEMES) * (len(POSES) + 7) + 1, len(files)
    print(f'{len(files)} brand files, {sum(path.stat().st_size for path in files) / 1048576:.1f} MiB')
    return palettes


def themes(brand):
    """The app's own light and dark palettes, so drawn interface panels use the shipped colors."""
    source = (REPO / 'lib/design/brand_palette_data.dart').read_text(encoding='utf-8')
    blocks = re.findall(r"BrandPalette\(\s*Accent\.(\w+),\s*Brightness\.(\w+),\s*\{(.*?)\},\s*\[(.*?)\],", source, re.S)
    assert len(blocks) == 12, len(blocks)
    lines = ['/* Generated by tool/site/export_assets.py from lib/design/brand_palette_data.dart; do not edit. */']
    for slug, mode, colors, ansi in blocks:
        pairs = re.findall(r"'([\w-]+)': Color\(0xFF(\w{6})\)", colors)
        codes = re.findall(r'Color\(0xFF(\w{6})\)', ansi)
        assert len(pairs) == 24 and len(codes) == 16, (slug, mode)
        rules = [f'--{name}:#{value}' for name, value in pairs]
        rules += [f'--ansi{index}:#{value}' for index, value in enumerate(codes)]
        if mode == 'light':
            rules += [f'--b-{name}:{value}' for name, value in brand[slug].items()]
        selector = f'[data-theme="{slug}"]' if mode == 'light' else f'[data-theme="{slug}"] [data-mode="dark"],[data-theme="{slug}"][data-mode="dark"]'
        lines.append(f'{selector}{{{";".join(rules)}}}')
    (SITE / 'themes.css').write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')


def data():
    clients = json.loads((REPO / 'tool/readme/benchmarks.json').read_text(encoding='utf-8'))['clients']
    assert round(sum(CONTENTS), 1) == 97.4 and clients[0]['name'] == 'Sshairy'
    rows = {
        'startup': [[row['name'], row['startup_seconds']] for row in clients],
        'memory': [[row['name'], row['idle_mib']] for row in clients],
        'download': DOWNLOAD,
        'contents': CONTENTS,
    }
    for name in ('startup', 'memory', 'download'):
        rows[name] = sorted(rows[name], key=lambda row: row[1])
        assert len({row[0] for row in rows[name]}) == len(rows[name]) and all(row[1] > 0 for row in rows[name])
    text = '// Generated by tool/site/export_assets.py from tool/readme/benchmarks.json; do not edit.\n'
    text += f'window.SSHAIRY_DATA = {json.dumps(rows, separators=(",", ":"))};\n'
    (OUT / 'data.js').write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    themes(artwork())
    data()
