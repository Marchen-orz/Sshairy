/// Indexes packaged root explanations without loading full specs at runtime.
/// Usage: `dart tool/generate_completion_command_metadata.dart <repository> [--check]`
library;

import 'dart:convert';
import 'dart:io';

import 'package:sshairy/features/terminal/domain/completion_spec.dart';

void main(List<String> args) {
  if (args.isEmpty || args.length > 2 || (args.length == 2 && args[1] != '--check')) {
    throw ArgumentError('Usage: dart tool/generate_completion_command_metadata.dart <repository> [--check]');
  }
  final repository = Directory(args.first);
  final manifest = jsonDecode(File('${repository.path}/assets/completions/manifest.json').readAsStringSync()) as Map;
  final commands = Map<String, String>.from(manifest['commands']);
  final names = commands.keys.toList()..sort();
  final output = StringBuffer(
    '''// Generated by tool/generate_completion_command_metadata.dart from packaged JSON; do not edit.

/// Root hints for command-name suggestions; full specifications remain lazily loaded.
class CompletionCommandMetadata {
  const CompletionCommandMetadata(this.description, {required this.canBrowse});

  final String? description;

  /// A static candidate, path source, child or nested spec can be browsed immediately after the command.
  /// Free text arguments alone do not advertise a next level.
  final bool canBrowse;
}

CompletionCommandMetadata? completionCommandMetadata(String command) => _commands[command];

// dart format off
const _commands = <String, CompletionCommandMetadata>{
''',
  );
  for (final command in names) {
    final path = commands[command]!;
    if (!RegExp(r'^assets/completions/specs/[^/\\]+\.json$').hasMatch(path) || path.contains('..')) {
      throw FormatException('Invalid packaged specification path: $path');
    }
    final spec = CompletionSpec.fromJson(jsonDecode(File('${repository.path}/$path').readAsStringSync()));
    // CompletionSpecs restores cd's omitted folder generator as a path template when loading the spec.
    final canBrowse = spec.canBrowse || spec.names.contains('cd');
    output.writeln(
      '  ${_dartString(command)}: CompletionCommandMetadata('
      '${_dartString(spec.description)}, canBrowse: $canBrowse),',
    );
  }
  output.write('};\n// dart format on\n');
  final file = File('${repository.path}/lib/features/terminal/domain/completion_command_metadata.dart');
  final content = output.toString();
  if (args.length == 2) {
    if (!file.existsSync() || file.readAsStringSync().replaceAll('\r\n', '\n') != content) {
      throw StateError('Completion command metadata is out of date');
    }
    stdout.writeln('Completion command metadata is current');
    return;
  }
  file.writeAsStringSync(content);
  stdout.writeln('Generated completion command metadata (${utf8.encode(content).length} bytes)');
}

String _dartString(String? value) => jsonEncode(value).replaceAll(r'$', r'\$');
