/// Returns an offline translation of a packaged specification's explanation.
/// A null result lets the view use a localized kind label and retain [CommandCandidate.detail] in a tooltip.
String? translatedCompletionDescription(String languageCode, CommandCandidate candidate) {
  final language = languageCode.toLowerCase().replaceAll('_', '-').split('-').first;
  final detail = candidate.detail;
  if (language != 'zh' || candidate.source != CommandCandidateSource.builtin || detail == null) return detail;
  // shortcut: only reviewed static descriptions are translated; expand this dictionary as uncovered tools are needed.
  return _chineseDescriptions[_descriptionKey(detail)];
}

String _descriptionKey(String text) =>
    text.trim().replaceAll(RegExp(r'\s+'), ' ').toLowerCase().replaceFirst(RegExp(r'\.$'), '');

