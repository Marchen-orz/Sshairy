/// Per-device capabilities granted on the desktop side.
class LinkPeerPermissions {
  const LinkPeerPermissions({
    this.allowMirror = true,
    this.allowProxy = true,
    this.allowFiles = false,
    this.allowSync = true,
    this.allowApproval = true,
  });

  final bool allowMirror;
  final bool allowProxy;
  final bool allowFiles;
  final bool allowSync;
  final bool allowApproval;

  LinkPeerPermissions copyWith({
    bool? allowMirror,
    bool? allowProxy,
    bool? allowFiles,
    bool? allowSync,
    bool? allowApproval,
  }) => LinkPeerPermissions(
    allowMirror: allowMirror ?? this.allowMirror,
    allowProxy: allowProxy ?? this.allowProxy,
    allowFiles: allowFiles ?? this.allowFiles,
    allowSync: allowSync ?? this.allowSync,
    allowApproval: allowApproval ?? this.allowApproval,
  );

  Map<String, Object?> toJson() => {
    'allowMirror': allowMirror,
    'allowProxy': allowProxy,
    'allowFiles': allowFiles,
    'allowSync': allowSync,
    'allowApproval': allowApproval,
  };

  factory LinkPeerPermissions.fromJson(Map<String, dynamic> j) => LinkPeerPermissions(
    allowMirror: j['allowMirror'] as bool? ?? true,
    allowProxy: j['allowProxy'] as bool? ?? true,
    allowFiles: j['allowFiles'] == true,
    allowSync: j['allowSync'] as bool? ?? true,
    allowApproval: j['allowApproval'] as bool? ?? true,
  );
}

/// A trusted peer stored in `link_peers.json`. Contains only public identity and preferences; never secrets.
class LinkPeer {
  const LinkPeer({
    required this.deviceId,
    required this.name,
    required this.publicKey,
    required this.pairedAt,
    this.lastSeen,
    this.lastAddress,
    this.lastPort,
    this.permissions = const LinkPeerPermissions(),
  });

  final String deviceId;
  final String name;
  final String publicKey;
  final DateTime pairedAt;
  final DateTime? lastSeen;
  final String? lastAddress;
  final int? lastPort;
  final LinkPeerPermissions permissions;

  LinkPeer copyWith({
    String? name,
    DateTime? lastSeen,
    String? lastAddress,
    int? lastPort,
    LinkPeerPermissions? permissions,
  }) => LinkPeer(
    deviceId: deviceId,
    name: name ?? this.name,
    publicKey: publicKey,
    pairedAt: pairedAt,
    lastSeen: lastSeen ?? this.lastSeen,
    lastAddress: lastAddress ?? this.lastAddress,
    lastPort: lastPort ?? this.lastPort,
    permissions: permissions ?? this.permissions,
  );

  Map<String, Object?> toJson() => {
    'deviceId': deviceId,
    'name': name,
    'publicKey': publicKey,
    'pairedAt': pairedAt.toUtc().toIso8601String(),
    if (lastSeen != null) 'lastSeen': lastSeen!.toUtc().toIso8601String(),
    if (lastAddress != null) 'lastAddress': lastAddress,
    if (lastPort != null) 'lastPort': lastPort,
    'permissions': permissions.toJson(),
  };

  factory LinkPeer.fromJson(Map<String, dynamic> j) {
    final id = j['deviceId'] as String? ?? '';
    final pub = j['publicKey'] as String? ?? '';
    if (id.isEmpty || pub.isEmpty) throw const FormatException('invalid peer');
    return LinkPeer(
      deviceId: id,
      name: j['name'] as String? ?? id,
      publicKey: pub,
      pairedAt: DateTime.parse(j['pairedAt'] as String),
      lastSeen: j['lastSeen'] == null ? null : DateTime.parse(j['lastSeen'] as String),
      lastAddress: j['lastAddress'] as String?,
      lastPort: j['lastPort'] as int?,
      permissions: j['permissions'] is Map
          ? LinkPeerPermissions.fromJson((j['permissions'] as Map).cast<String, dynamic>())
          : const LinkPeerPermissions(),
    );
  }
}

/// Short-lived single-use pairing code and URI generated by the desktop host.
class LinkPairingInfo {
  const LinkPairingInfo({
    required this.code,
    required this.deviceId,
    required this.deviceName,
    required this.publicKey,
    required this.host,
    required this.port,
    required this.expiresAt,
  });

  final String code;
  final String deviceId;
  final String deviceName;
  final String publicKey;
  final String host;
  final int port;
  final DateTime expiresAt;

  bool get isExpired => DateTime.now().isAfter(expiresAt);

  String toUri() => Uri(
    scheme: 'sshairy-link',
    host: 'pair',
    queryParameters: {
      'v': '$linkProtocolVersion',
      'h': '$host:$port',
      'id': deviceId,
      'pk': publicKey,
      'c': code,
      'n': deviceName,
    },
  ).toString();

  static LinkPairingInfo? parseUri(String raw) {
    final uri = Uri.tryParse(raw.trim());
    if (uri == null || uri.scheme != 'sshairy-link' || uri.host != 'pair') return null;
    final endpoint = uri.queryParameters['h'] ?? '';
    final sep = endpoint.lastIndexOf(':');
    if (sep <= 0) return null;
    final host = endpoint.substring(0, sep).trim();
    final port = int.tryParse(endpoint.substring(sep + 1));
    final code = (uri.queryParameters['c'] ?? '').trim();
    final pk = (uri.queryParameters['pk'] ?? '').trim();
    final id = (uri.queryParameters['id'] ?? '').trim();
    final name = (uri.queryParameters['n'] ?? host).trim();
    if (host.isEmpty || port == null || port < 1 || port > 65535 || code.length < 6) return null;
    return LinkPairingInfo(
      code: code,
      deviceId: id,
      deviceName: name.isEmpty ? host : name,
      publicKey: pk,
      host: host,
      port: port,
      expiresAt: DateTime.now().add(const Duration(minutes: 3)),
    );
  }
}

